-- ----------------------------------------------------------------------------
-- PASSO 8. MUTATING TABLE (ORA-04091)  -- erro proposital
-- ----------------------------------------------------------------------------
-- Regra: no maximo 2 alunos por turma (limite pequeno para testar rapido)
CREATE OR REPLACE TRIGGER trg_valida_max_alunos
    AFTER INSERT ON matricula
    FOR EACH ROW
DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count
      FROM matricula WHERE turma_id = :NEW.turma_id;   -- le a propria tabela!
    IF v_count > 2 THEN
        RAISE_APPLICATION_ERROR(-20003, 'Turma ' || :NEW.turma_id || ' lotada!');
    END IF;
END;
/

-- Qualquer INSERT dispara ORA-04091: a trigger AFTER de linha le a tabela
-- que esta sendo modificada
INSERT INTO matricula (aluno_id, turma_id) VALUES (1, 1);
ROLLBACK;


-- ----------------------------------------------------------------------------
-- PASSO 9. COMPOUND TRIGGER: a solucao para a mutating table
-- ----------------------------------------------------------------------------
DROP TRIGGER trg_valida_max_alunos;

CREATE OR REPLACE TRIGGER trg_valida_max_alunos
    FOR INSERT ON matricula
    COMPOUND TRIGGER

    TYPE t_turmas IS TABLE OF NUMBER INDEX BY PLS_INTEGER;
    v_turmas t_turmas;

    AFTER EACH ROW IS
    BEGIN
        -- so guarda, nao consulta
        v_turmas(v_turmas.COUNT + 1) := :NEW.turma_id;
    END AFTER EACH ROW;

    AFTER STATEMENT IS
        v_count NUMBER;
    BEGIN
        FOR i IN 1 .. v_turmas.COUNT LOOP
            SELECT COUNT(*) INTO v_count FROM matricula WHERE turma_id = v_turmas(i);
            IF v_count > 2 THEN
                RAISE_APPLICATION_ERROR(-20003, 'Turma ' || v_turmas(i) || ' lotada!');
            END IF;
        END LOOP;
    END AFTER STATEMENT;
END trg_valida_max_alunos;
/

