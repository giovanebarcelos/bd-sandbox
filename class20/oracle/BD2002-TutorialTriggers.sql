-- 4b. Pedido ja enviado nao pode mudar
CREATE OR REPLACE TRIGGER trg_bloqueia_update_pedido
    BEFORE UPDATE ON pedido_loja
    FOR EACH ROW
BEGIN
    IF :OLD.status = 'ENVIADO' THEN
        RAISE_APPLICATION_ERROR(-20002,
            'Nao e permitido alterar pedido com status ENVIADO (pedido ' || :OLD.pedido_id || ')');
    END IF;
END;
/

