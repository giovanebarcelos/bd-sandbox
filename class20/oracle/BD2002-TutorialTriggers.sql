-- ----------------------------------------------------------------------------
-- PASSO 5. UPDATE OF coluna + WHEN: so dispara quando o preco muda
-- ----------------------------------------------------------------------------
CREATE TABLE historico_preco (
    id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produto_id    NUMBER,
    preco_antigo  NUMBER(10,2),
    preco_novo    NUMBER(10,2),
    data_hora     TIMESTAMP DEFAULT SYSTIMESTAMP
);

-- Atencao: dentro do WHEN se escreve NEW/OLD SEM os dois-pontos
CREATE OR REPLACE TRIGGER trg_historico_preco
    AFTER UPDATE OF preco ON produto
    FOR EACH ROW
    WHEN (OLD.preco <> NEW.preco)
BEGIN
    INSERT INTO historico_preco (produto_id, preco_antigo, preco_novo)
    VALUES (:NEW.produto_id, :OLD.preco, :NEW.preco);
END;
/

-- nao mexe no preco
UPDATE produto SET nome = 'Pen drive 64 GB' WHERE produto_id = 2;
-- mesmo preco
UPDATE produto SET preco = 59.90 WHERE produto_id = 2;
-- preco mudou
UPDATE produto SET preco = 54.90 WHERE produto_id = 2;
COMMIT;

SELECT produto_id, preco_antigo, preco_novo FROM historico_preco ORDER BY id;


