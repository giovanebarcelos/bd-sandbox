-- 4a. Datas da turma
CREATE OR REPLACE TRIGGER trg_valida_turma_datas
    BEFORE INSERT OR UPDATE ON turma
    FOR EACH ROW
BEGIN
    IF :NEW.data_final < :NEW.data_inicial THEN
        RAISE_APPLICATION_ERROR(-20001,
            'Data final (' || TO_CHAR(:NEW.data_final, 'DD/MM/YYYY') ||
            ') nao pode ser anterior a data inicial (' ||
            TO_CHAR(:NEW.data_inicial, 'DD/MM/YYYY') || ')');
    END IF;
END;
/

