-- DespensaViva · Oracle · 01_ddl.sql
-- Cozinha comunitária: insumos em lotes com validade; o consumo segue FEFO (vence primeiro, sai primeiro).
-- Constraints sempre nomeadas (pk_, uk_, fk_, ck_). Diferenças em relação ao PostgreSQL:
--   VARCHAR2 e NUMBER no lugar de VARCHAR e NUMERIC · TRUNC(SYSDATE) no lugar de CURRENT_DATE
--   Oracle NÃO tem "ON DELETE RESTRICT": omitir a cláusula já bloqueia o DELETE do pai (ORA-02292).

CREATE TABLE categoria (
    categoria_id  NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nome          VARCHAR2(60) NOT NULL,
    CONSTRAINT pk_categoria      PRIMARY KEY (categoria_id),
    CONSTRAINT uk_categoria_nome UNIQUE (nome)
);

CREATE TABLE fornecedor (
    fornecedor_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nome          VARCHAR2(100) NOT NULL,
    tipo          VARCHAR2(10)  NOT NULL,
    CONSTRAINT pk_fornecedor      PRIMARY KEY (fornecedor_id),
    CONSTRAINT uk_fornecedor_nome UNIQUE (nome),
    CONSTRAINT ck_fornecedor_tipo CHECK (tipo IN ('DOADOR', 'COMERCIO'))
);

CREATE TABLE insumo (
    insumo_id       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nome            VARCHAR2(80)  NOT NULL,
    unidade         VARCHAR2(3)   NOT NULL,
    estoque_minimo  NUMBER(10,3)  DEFAULT 0 NOT NULL,
    categoria_id    NUMBER        NOT NULL,
    CONSTRAINT pk_insumo        PRIMARY KEY (insumo_id),
    CONSTRAINT uk_insumo_nome   UNIQUE (nome),
    CONSTRAINT ck_insumo_unid   CHECK (unidade IN ('KG', 'L', 'UN')),
    CONSTRAINT ck_insumo_min    CHECK (estoque_minimo >= 0),
    CONSTRAINT fk_insumo_categ  FOREIGN KEY (categoria_id) REFERENCES categoria (categoria_id)
);

CREATE TABLE lote (
    lote_id            NUMBER GENERATED BY DEFAULT AS IDENTITY,
    insumo_id          NUMBER        NOT NULL,
    fornecedor_id      NUMBER        NOT NULL,
    quantidade_inicial NUMBER(10,3)  NOT NULL,
    quantidade_atual   NUMBER(10,3)  NOT NULL,
    data_entrada       DATE          DEFAULT TRUNC(SYSDATE) NOT NULL,
    data_validade      DATE          NOT NULL,
    CONSTRAINT pk_lote         PRIMARY KEY (lote_id),
    CONSTRAINT ck_lote_inicial CHECK (quantidade_inicial > 0),
    CONSTRAINT ck_lote_atual   CHECK (quantidade_atual >= 0 AND quantidade_atual <= quantidade_inicial),
    CONSTRAINT ck_lote_datas   CHECK (data_validade >= data_entrada),
    CONSTRAINT fk_lote_insumo  FOREIGN KEY (insumo_id)     REFERENCES insumo (insumo_id),
    CONSTRAINT fk_lote_forn    FOREIGN KEY (fornecedor_id) REFERENCES fornecedor (fornecedor_id)
);

CREATE TABLE movimentacao (
    mov_id     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    lote_id    NUMBER        NOT NULL,
    tipo       VARCHAR2(10)  NOT NULL,
    quantidade NUMBER(10,3)  NOT NULL,
    data_hora  TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    motivo     VARCHAR2(100),
    CONSTRAINT pk_movimentacao   PRIMARY KEY (mov_id),
    CONSTRAINT ck_mov_tipo       CHECK (tipo IN ('ENTRADA', 'CONSUMO', 'DESCARTE')),
    CONSTRAINT ck_mov_quantidade CHECK (quantidade > 0),
    CONSTRAINT fk_mov_lote       FOREIGN KEY (lote_id) REFERENCES lote (lote_id)
);

CREATE TABLE receita (
    receita_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nome       VARCHAR2(80) NOT NULL,
    porcoes    NUMBER(5)    NOT NULL,
    CONSTRAINT pk_receita      PRIMARY KEY (receita_id),
    CONSTRAINT uk_receita_nome UNIQUE (nome),
    CONSTRAINT ck_receita_porc CHECK (porcoes > 0)
);

-- Entidade associativa do N:M receita x insumo (carrega a quantidade por porção).
CREATE TABLE receita_insumo (
    receita_id            NUMBER        NOT NULL,
    insumo_id             NUMBER        NOT NULL,
    quantidade_por_porcao NUMBER(10,3)  NOT NULL,
    CONSTRAINT pk_receita_insumo PRIMARY KEY (receita_id, insumo_id),
    CONSTRAINT ck_ri_quantidade  CHECK (quantidade_por_porcao > 0),
    CONSTRAINT fk_ri_receita     FOREIGN KEY (receita_id) REFERENCES receita (receita_id) ON DELETE CASCADE,
    CONSTRAINT fk_ri_insumo      FOREIGN KEY (insumo_id)  REFERENCES insumo (insumo_id)
);

-- Trilha de auditoria alimentada pelo trigger trg_lote_auditoria (procedures/oracle_procedures.sql).
CREATE TABLE auditoria_lote (
    aud_id        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    lote_id       NUMBER        NOT NULL,
    operacao      VARCHAR2(10)  NOT NULL,
    qtd_antes     NUMBER(10,3),
    qtd_depois    NUMBER(10,3),
    usuario_banco VARCHAR2(100) NOT NULL,
    data_hora     TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_auditoria_lote PRIMARY KEY (aud_id)
);
