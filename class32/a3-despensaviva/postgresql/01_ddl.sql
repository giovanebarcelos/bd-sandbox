-- DespensaViva · PostgreSQL · 01_ddl.sql
-- Cozinha comunitária: insumos em lotes com validade; o consumo segue FEFO (vence primeiro, sai primeiro).
-- Constraints sempre nomeadas (pk_, uk_, fk_, ck_) e ON DELETE explícito em toda chave estrangeira.

CREATE TABLE categoria (
    categoria_id  INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nome          VARCHAR(60) NOT NULL,
    CONSTRAINT pk_categoria      PRIMARY KEY (categoria_id),
    CONSTRAINT uk_categoria_nome UNIQUE (nome)
);

CREATE TABLE fornecedor (
    fornecedor_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nome          VARCHAR(100) NOT NULL,
    tipo          VARCHAR(10)  NOT NULL,
    CONSTRAINT pk_fornecedor      PRIMARY KEY (fornecedor_id),
    CONSTRAINT uk_fornecedor_nome UNIQUE (nome),
    CONSTRAINT ck_fornecedor_tipo CHECK (tipo IN ('DOADOR', 'COMERCIO'))
);

CREATE TABLE insumo (
    insumo_id       INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nome            VARCHAR(80)   NOT NULL,
    unidade         VARCHAR(3)    NOT NULL,
    estoque_minimo  NUMERIC(10,3) DEFAULT 0 NOT NULL,
    categoria_id    INTEGER       NOT NULL,
    CONSTRAINT pk_insumo        PRIMARY KEY (insumo_id),
    CONSTRAINT uk_insumo_nome   UNIQUE (nome),
    CONSTRAINT ck_insumo_unid   CHECK (unidade IN ('KG', 'L', 'UN')),
    CONSTRAINT ck_insumo_min    CHECK (estoque_minimo >= 0),
    CONSTRAINT fk_insumo_categ  FOREIGN KEY (categoria_id) REFERENCES categoria (categoria_id) ON DELETE RESTRICT
);

CREATE TABLE lote (
    lote_id            INTEGER GENERATED BY DEFAULT AS IDENTITY,
    insumo_id          INTEGER       NOT NULL,
    fornecedor_id      INTEGER       NOT NULL,
    quantidade_inicial NUMERIC(10,3) NOT NULL,
    quantidade_atual   NUMERIC(10,3) NOT NULL,
    data_entrada       DATE          NOT NULL DEFAULT CURRENT_DATE,
    data_validade      DATE          NOT NULL,
    CONSTRAINT pk_lote         PRIMARY KEY (lote_id),
    CONSTRAINT ck_lote_inicial CHECK (quantidade_inicial > 0),
    CONSTRAINT ck_lote_atual   CHECK (quantidade_atual >= 0 AND quantidade_atual <= quantidade_inicial),
    CONSTRAINT ck_lote_datas   CHECK (data_validade >= data_entrada),
    CONSTRAINT fk_lote_insumo  FOREIGN KEY (insumo_id)     REFERENCES insumo (insumo_id)         ON DELETE RESTRICT,
    CONSTRAINT fk_lote_forn    FOREIGN KEY (fornecedor_id) REFERENCES fornecedor (fornecedor_id) ON DELETE RESTRICT
);

CREATE TABLE movimentacao (
    mov_id     INTEGER GENERATED BY DEFAULT AS IDENTITY,
    lote_id    INTEGER       NOT NULL,
    tipo       VARCHAR(10)   NOT NULL,
    quantidade NUMERIC(10,3) NOT NULL,
    data_hora  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    motivo     VARCHAR(100),
    CONSTRAINT pk_movimentacao   PRIMARY KEY (mov_id),
    CONSTRAINT ck_mov_tipo       CHECK (tipo IN ('ENTRADA', 'CONSUMO', 'DESCARTE')),
    CONSTRAINT ck_mov_quantidade CHECK (quantidade > 0),
    CONSTRAINT fk_mov_lote       FOREIGN KEY (lote_id) REFERENCES lote (lote_id) ON DELETE RESTRICT
);

CREATE TABLE receita (
    receita_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nome       VARCHAR(80) NOT NULL,
    porcoes    INTEGER     NOT NULL,
    CONSTRAINT pk_receita      PRIMARY KEY (receita_id),
    CONSTRAINT uk_receita_nome UNIQUE (nome),
    CONSTRAINT ck_receita_porc CHECK (porcoes > 0)
);

-- Entidade associativa do N:M receita x insumo (carrega a quantidade por porção).
CREATE TABLE receita_insumo (
    receita_id            INTEGER       NOT NULL,
    insumo_id             INTEGER       NOT NULL,
    quantidade_por_porcao NUMERIC(10,3) NOT NULL,
    CONSTRAINT pk_receita_insumo PRIMARY KEY (receita_id, insumo_id),
    CONSTRAINT ck_ri_quantidade  CHECK (quantidade_por_porcao > 0),
    CONSTRAINT fk_ri_receita     FOREIGN KEY (receita_id) REFERENCES receita (receita_id) ON DELETE CASCADE,
    CONSTRAINT fk_ri_insumo      FOREIGN KEY (insumo_id)  REFERENCES insumo (insumo_id)   ON DELETE RESTRICT
);

-- Trilha de auditoria alimentada pelo trigger trg_lote_auditoria (procedures/postgresql_procedures.sql).
CREATE TABLE auditoria_lote (
    aud_id        INTEGER GENERATED BY DEFAULT AS IDENTITY,
    lote_id       INTEGER       NOT NULL,
    operacao      VARCHAR(10)   NOT NULL,
    qtd_antes     NUMERIC(10,3),
    qtd_depois    NUMERIC(10,3),
    usuario_banco VARCHAR(100)  NOT NULL,
    data_hora     TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_auditoria_lote PRIMARY KEY (aud_id)
);
